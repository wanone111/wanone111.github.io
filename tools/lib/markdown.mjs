import { readdir, readFile } from 'node:fs/promises';
import { basename, dirname, extname, resolve } from 'node:path';
import { parse, stringify } from 'yaml';
import { pathExists, relativePosix, sha256, walkFiles } from './files.mjs';

const GENERATED_MARKER = '<!-- GENERATED FROM THE PRIVATE KNOWLEDGE BASE. DO NOT EDIT THIS FILE. -->';
const FRONTMATTER = /^\uFEFF?---\s*\r?\n([\s\S]*?)\r?\n---\s*(?:\r?\n|$)/;

export function parseMarkdown(raw, file = '<content>') {
  const normalized = raw.replace(/^\uFEFF/, '');
  const match = normalized.match(FRONTMATTER);
  if (!match) throw new Error(`${file}: missing YAML front matter.`);

  let data;
  try {
    data = parse(match[1]);
  } catch (error) {
    throw new Error(`${file}: invalid YAML front matter: ${error.message}`);
  }
  if (!data || typeof data !== 'object' || Array.isArray(data)) {
    throw new Error(`${file}: front matter must be a YAML object.`);
  }

  return {
    data,
    body: normalized.slice(match[0].length),
    raw: normalized,
  };
}

export function hasGeneratedMarker(text) {
  const header = text.match(FRONTMATTER);
  return Boolean(header && text.startsWith(GENERATED_MARKER, header[0].length));
}

export function serializeMarkdown(data, body) {
  const yaml = stringify(data, { lineWidth: 0 }).trimEnd();
  return `---\n${yaml}\n---\n\n${GENERATED_MARKER}\n\n${body.trim()}\n`;
}

const ALLOWED_EXTENSIONS = new Set(['.avif', '.gif', '.jpeg', '.jpg', '.png', '.svg', '.webp']);

function normalizeTarget(value) {
  return decodeURIComponent(value.trim().replace(/^<|>$/g, '')).replace(/\\/g, '/').replace(/^\.\//, '');
}

function stableStem(value) {
  const stem = value
    .normalize('NFKD')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 48);
  return stem || 'asset';
}

function isImageTarget(target) {
  return ALLOWED_EXTENSIONS.has(extname(target).toLowerCase());
}

export async function listStaleOutputs(paths, nextPages = new Map()) {
  const stale = new Set();
  const oldImages = new Map();
  const keptText = [...nextPages.values()];
  for (const root of new Set([paths.generatedContentRoot, paths.generatedDocsRoot])) {
    if (!await pathExists(root)) continue;
    for (const file of await walkFiles(root, (path) => /\.mdx?$/i.test(path))) {
      const text = await readFile(file, 'utf8');
      if (!hasGeneratedMarker(text)) {
        keptText.push(text);
        continue;
      }
      const path = resolve(file);
      if (!nextPages.has(path)) stale.add(path);
      for (const [, name, hash] of text.matchAll(/!\[[^\]\r\n]*\]\(\/images\/generated\/([a-z0-9-]{1,48}-([a-f0-9]{12})\.[a-z]+)\)/g)) {
        if (isImageTarget(name)) oldImages.set(name, hash);
      }
    }
  }

  if (!oldImages.size || !await pathExists(paths.generatedAssetsRoot)) return stale;
  for (const entry of await readdir(paths.generatedAssetsRoot, { withFileTypes: true })) {
    const hash = oldImages.get(entry.name);
    if (!entry.isFile() || !hash || keptText.some((text) => text.includes(entry.name))) continue;
    const path = resolve(paths.generatedAssetsRoot, entry.name);
    if (sha256(await readFile(path)).startsWith(hash)) stale.add(path);
  }
  return stale;
}

export async function createAssetManager(paths) {
  const sourceFiles = await pathExists(paths.assetsRoot) ? await walkFiles(paths.assetsRoot, isImageTarget) : [];
  const indexedPaths = new Set(sourceFiles.map((file) => resolve(file)));
  const byRelative = new Map();
  const byBasename = new Map();

  for (const file of sourceFiles) {
    const relative = relativePosix(paths.assetsRoot, file).toLowerCase();
    byRelative.set(relative, file);
    const name = basename(file).toLowerCase();
    const list = byBasename.get(name) ?? [];
    list.push(file);
    byBasename.set(name, list);
  }

  const outputs = new Map();

  function findSource(note, rawTarget) {
    const target = normalizeTarget(rawTarget);
    if (!isImageTarget(target)) throw new Error(`${note.relativePath}: unsupported or non-image embed: ${rawTarget}`);

    const noteRelativeCandidate = resolve(dirname(note.file), target);
    if (indexedPaths.has(noteRelativeCandidate)) return noteRelativeCandidate;

    const rootCandidate = resolve(paths.assetsRoot, target);
    if (indexedPaths.has(rootCandidate)) return rootCandidate;

    const exact = byRelative.get(target.toLowerCase());
    if (exact) return exact;

    const matches = byBasename.get(basename(target).toLowerCase()) ?? [];
    if (matches.length === 1) return matches[0];
    if (matches.length > 1) throw new Error(`${note.relativePath}: ambiguous attachment name "${rawTarget}"; use a path relative to _assets.`);
    throw new Error(`${note.relativePath}: attachment not found in _assets: ${rawTarget}`);
  }

  async function resolveAsset(note, rawTarget) {
    const source = findSource(note, rawTarget);
    const bytes = await readFile(source);
    const hash = sha256(bytes);
    const extension = extname(source).toLowerCase();
    const filename = `${stableStem(basename(source, extension))}-${hash.slice(0, 12)}${extension}`;
    const outputPath = resolve(paths.generatedAssetsRoot, filename);
    const url = `/images/generated/${filename}`;
    if (!outputs.has(outputPath)) outputs.set(outputPath, { outputPath, bytes });
    return url;
  }

  return { resolveAsset, outputs };
}

function buildLinkIndex(notes) {
  const index = new Map();
  const ambiguous = new Set();
  for (const note of notes) {
    const relativeKey = note.relativePath.replace(/\.[^.]+$/, '');
    const keys = [note.data.title, note.data.slug, basename(note.file, extname(note.file)), relativeKey];
    if (note.folder === '笔记' && relativeKey.startsWith('笔记/')) {
      keys.push(`blog/${relativeKey.slice('笔记/'.length)}`);
      keys.push(`blog/${note.data.slug}`);
    }
    for (const raw of keys) {
      const key = String(raw).trim().toLocaleLowerCase('zh-CN').replace(/\\/g, '/');
      if (!key) continue;
      if (index.has(key) && index.get(key).route !== note.route) ambiguous.add(key);
      else index.set(key, note);
    }
  }
  return { index, ambiguous };
}

const CALLOUT_LABELS = {
  note: '说明',
  abstract: '摘要',
  info: '信息',
  todo: '待办',
  tip: '提示',
  success: '成功',
  question: '问题',
  warning: '警告',
  caution: '注意',
  failure: '失败',
  danger: '危险',
  bug: '缺陷',
  problem: '故障现象',
  environment: '实验环境',
  diagnosis: '排查过程',
  conclusion: '关键结论',
  solution: '可复用方案',
  limitations: '已知限制',
  validation: '验证结果',
  example: '示例',
  quote: '引用',
};

const CODE_LANGUAGE_ALIASES = new Map([
  ['c', 'c'],
  ['c++', 'cpp'],
  ['cpp', 'cpp'],
  ['txt', 'text'],
  ['text', 'text'],
  ['shell', 'bash'],
  ['bash', 'bash'],
]);

async function replaceAsync(input, pattern, replacer) {
  const matches = [...input.matchAll(pattern)];
  if (matches.length === 0) return input;
  const replacements = await Promise.all(matches.map((match) => replacer(...match)));
  let index = 0;
  return input.replace(pattern, () => replacements[index++]);
}

function headingAnchor(value) {
  return value.trim().toLocaleLowerCase('zh-CN').replace(/[\s_]+/g, '-').replace(/[^\p{L}\p{N}-]/gu, '');
}

function convertCallouts(markdown) {
  return markdown.replace(/^>[ \t]*\[!([a-z]+)\][+-]?[ \t]*([^\r\n]*)$/gim, (_match, kind, title) => {
    const normalizedKind = kind.toLowerCase();
    const label = CALLOUT_LABELS[normalizedKind] ?? kind;
    return `> <span class="tech-callout__marker" data-tech-callout="${normalizedKind}" aria-hidden="true"></span> **${label}${title.trim() ? `：${title.trim()}` : ''}**`;
  });
}

function normalizeCodeFenceLanguages(markdown) {
  return markdown.replace(/^```[ \t]*([^`\s]+)[ \t]*$/gm, (full, language) => {
    const normalized = CODE_LANGUAGE_ALIASES.get(language.toLowerCase());
    return normalized ? `\`\`\`${normalized}` : full;
  });
}

export function createWikiResolver(notes) {
  const { index, ambiguous } = buildLinkIndex(notes);
  return function resolveWiki(note, target) {
    const [rawPage, rawHeading] = target.split('#', 2);
    let route = note.route;
    if (rawPage.trim()) {
      const key = rawPage.trim().toLocaleLowerCase('zh-CN').replace(/\\/g, '/');
      if (ambiguous.has(key)) throw new Error(`${note.relativePath}: ambiguous Wikilink target "${rawPage}".`);
      const linked = index.get(key);
      if (!linked) throw new Error(`${note.relativePath}: unresolved Wikilink target "${rawPage}".`);
      route = linked.route;
    }
    if (rawHeading) route += `#${headingAnchor(rawHeading)}`;
    return route;
  };
}

export async function convertMarkdown(note, { resolveWiki, resolveAsset }) {
  let output = normalizeCodeFenceLanguages(convertCallouts(note.body));

  output = await replaceAsync(output, /!\[\[([^\]]+)\]\]/g, async (_full, value) => {
    const [target] = value.split('|', 1);
    if (!isImageTarget(target)) throw new Error(`${note.relativePath}: embedded notes are unsupported; link to the note instead: ${target}`);
    const url = await resolveAsset(note, target);
    const alt = basename(target, extname(target)).replace(/[-_]+/g, ' ');
    return `![${alt}](${url})`;
  });

  output = output.replace(/(?<!!)\[\[([^\]|]+)(?:\|([^\]]+))?\]\]/g, (_full, target, label) => {
    const route = resolveWiki(note, target);
    const display = (label || target.split('#').at(-1)).trim().replace(/[\[\]]/g, '');
    return `[${display}](${route})`;
  });

  output = await replaceAsync(output, /!\[([^\]]*)\]\(([^)]+)\)/g, async (full, alt, target) => {
    const cleanTarget = target.trim().split(/\s+["']/)[0];
    if (/^(?:https?:|data:|\/|#)/i.test(cleanTarget)) return full;
    const url = await resolveAsset(note, cleanTarget);
    return `![${alt}](${url})`;
  });

  return output;
}
